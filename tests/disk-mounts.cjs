const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const {spawnSync} = require('node:child_process');
const work=fs.mkdtempSync(path.join(process.env.TMPDIR,'zs-disks.'));
console.log('Retained disk scratch:',work);
const source=fs.readFileSync(__dirname+'/../shell/SysStats.qml','utf8');
const command=source.match(/id: extraStatsProcess\n        command: (.+)/)[1];
const context=vm.createContext({Theme:{diskMounts:['/','/custom home','/mount;$literal']},sysstatsScriptPath:path.join(work,'sysstats.sh')});
context.root=context;
fs.copyFileSync(__dirname+'/../shell/scripts/sysstats.sh',context.sysstatsScriptPath);
fs.writeFileSync(path.join(work,'cat'),'#!/bin/sh\nexit 1\n',{mode:0o700});
fs.writeFileSync(path.join(work,'df'),`#!${process.execPath}\nconst fs=require('node:fs');fs.writeFileSync(process.env.ZS_TRACE,JSON.stringify(process.argv.slice(2)));console.log('Mounted on Size Used\\n/ 100 20\\n/custom home 200 30\\n/mount;$literal 300 40');`,{mode:0o700});
const tail=spawnSync('/bin/sh',['-c','command -v tail'],{encoding:'utf8'}).stdout.trim();fs.symlinkSync(tail,path.join(work,'tail'));
const args=Array.from(vm.runInContext(command,context));
const result=spawnSync('/bin/sh',args.slice(1),{encoding:'utf8',env:{PATH:work,HOME:'/custom home',XDG_CONFIG_HOME:work,ZS_TRACE:path.join(work,'trace'),DBUS_SESSION_BUS_ADDRESS:'unix:path=/nonexistent/zs-test',DBUS_SYSTEM_BUS_ADDRESS:'unix:path=/nonexistent/zs-test'}});
assert.equal(result.status,0,result.stderr);
assert.deepEqual(JSON.parse(fs.readFileSync(path.join(work,'trace'),'utf8')),['-B1','--output=target,size,used','--','/','/custom home','/mount;$literal'],'Disk paths must remain separate argv operands');
vm.runInContext(source.match(/^    function parseExtraStats\([^\n]*\) \{[\s\S]*?^    \}/m)[0],context);
context.parseExtraStats(result.stdout+'bad malformed line\n/duplicate 100 bad\n/ 100 20\n');
assert.deepEqual(JSON.parse(JSON.stringify(context.disks)),[{mount:'/',size:100,used:20},{mount:'/custom home',size:200,used:30},{mount:'/mount;$literal',size:300,used:40}]);
console.log('PASS argv-safe configured disks and whitespace-safe actual mount parsing');
